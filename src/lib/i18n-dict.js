export function translate(key, lang) {
  if (lang !== 'en' || typeof key !== 'string') return key;
  return EN[key] ?? key;
}
// Interpolated strings: translate the pattern, then fill {placeholders}.
export function format(pattern, vars = {}) {
  return String(pattern).replace(/\{(\w+)\}/g, (match, name) => (name in vars ? String(vars[name]) : match));
}
export function translateError(message, lang) {
  if (lang !== 'en' || typeof message !== 'string') return message;
  return EN_ERRORS[message] ?? message;
}
